CREATE VIEW WORK_EFFORT_MEASURE_RAT_SC_VIEW (
	WORK_EFFORT_MEASURE_ID,
	UOM_ID,
	UOM_RATING_VALUE,
	UOM_CODE,
	UOM_CODE_LANG,
	UOM_DESCR,
	UOM_DESCR_LANG
) AS (
	SELECT 
		WEM.WORK_EFFORT_MEASURE_ID,
		ARS.UOM_ID,
		ARS.UOM_RATING_VALUE,
		ARS.UOM_CODE,
		ARS.UOM_CODE_LANG,
		UM.DESCRIPTION AS UOM_DESCR,
		UM.DESCRIPTION_LANG AS UOM_DESCR_LANG
	FROM
		WORK_EFFORT_MEASURE WEM
	JOIN
		GL_ACCOUNT AC
	ON
		AC.GL_ACCOUNT_ID = WEM.GL_ACCOUNT_ID
	JOIN
		UOM UM
	ON
		UM.UOM_ID = AC.DEFAULT_UOM_ID
	JOIN
		GL_ACCOUNT_MEAS_RAT_SC ARS
	ON
		ARS.GL_ACCOUNT_ID = AC.GL_ACCOUNT_ID
	WHERE
		UM.UOM_TYPE_ID = 'RATING_SCALE'
);