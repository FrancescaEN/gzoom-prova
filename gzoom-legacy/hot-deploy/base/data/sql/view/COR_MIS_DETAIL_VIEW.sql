CREATE VIEW COR_MIS_DETAIL_VIEW AS
select 
  PDO.CUSTOM_TIME_PERIOD_CODE AS ANNO,
  ARE.ETCH AS ETCH_AREA_RISCHIO,
  ARE.WORK_EFFORT_NAME AS AREA_RISCHIO,
  PRO.SOURCE_REFERENCE_ID AS COD_PROCESSO,
  PRO.ETCH AS ETCH_PROCESSO,
  PRO.WORK_EFFORT_NAME AS PROCESSO,
  FAS.WORK_EFFORT_NAME AS FASE_O_SOTTOPROCESSO,
  RIS.WORK_EFFORT_NAME AS RISCHIO,
  MIS.work_effort_id,
  MIS.WORK_EFFORT_NAME AS MISURA,
  TIP.WORK_EFFORT_PURPOSE_TYPE_CODE AS ETCH_TIPO_MISURA,
  TIP.DESCRIPTION AS TIPO_MISURA,
  concat('Lang. ',PDO.CUSTOM_TIME_PERIOD_CODE) AS ANNO_LANG,
  concat('Lang. ',ARE.WORK_EFFORT_NAME) AS AREA_RISCHIO_LANG,
  concat('Lang. ',PRO.WORK_EFFORT_NAME) AS PROCESSO_LANG,
  concat('Lang. ',FAS.WORK_EFFORT_NAME) AS FASE_O_SOTTOPROCESSO_LANG,
  concat('Lang. ',RIS.WORK_EFFORT_NAME) AS RISCHIO_LANG,
  concat('Lang. ',MIS.WORK_EFFORT_NAME) AS MISURA_LANG,
  concat('Lang. ',TIP.DESCRIPTION) AS TIPO_MISURA_LANG,
  CASE WHEN MISSAL_AMOUNT IS NULL THEN 1 ELSE 0 END AS SAL_MONITORATA,
  CASE WHEN MISSAL_AMOUNT = 10 THEN 1 ELSE 0 END AS SAL_ATTUATA,
  CASE WHEN MISSAL_AMOUNT = 20 THEN 1 ELSE 0 END AS SAL_IN_CORSO,
  CASE WHEN MISSAL_AMOUNT = 30 THEN 1 ELSE 0 END AS SAL_DA_AVVIARE,
  CASE WHEN MISSAL_AMOUNT = 40 THEN 1 ELSE 0 END AS SAL_RITARDO,
  CASE WHEN MISOST_AMOUNT IS NULL THEN 1 ELSE 0 END AS OST_NESSUNO,
  CASE WHEN MISOST_AMOUNT = 10 THEN 1 ELSE 0 END AS OST_PERSONALE,
  CASE WHEN MISOST_AMOUNT = 20 THEN 1 ELSE 0 END AS OST_FINANZIARIO,
  CASE WHEN MISOST_AMOUNT = 30 THEN 1 ELSE 0 END AS OST_COMPETENZE,
  CASE WHEN MISOST_AMOUNT = 40 THEN 1 ELSE 0 END AS OST_ALTRO,
  CASE WHEN MISIDO_AMOUNT = 10 THEN 1 ELSE 0 END AS IDO_IDONEO,
  CASE WHEN MISIDO_AMOUNT = 20 THEN 1 ELSE 0 END AS IDO_NON_IDONEO,
  CASE WHEN MISIDO_AMOUNT = 30 OR MISIDO_AMOUNT IS NULL THEN 1 ELSE 0 END AS IDO_DA_VALUTARE,
  CASE 
  	WHEN MISSAL_NOTA IS NULL THEN N115.NOTE_INFO
  	ELSE CONCAT(MISSAL_NOTA,CONCAT( '; ', N115.NOTE_INFO))
  END AS NOTA_ATTUAZIONE,
  CASE 
  	WHEN MISOST_NOTA IS NULL THEN N125.NOTE_INFO
  	ELSE CONCAT(MISOST_NOTA,CONCAT( '; ', N125.NOTE_INFO))
  END AS NOTA_OSTATIVA,
  CASE 
  	WHEN MISIDO_NOTA IS NULL THEN N130.NOTE_INFO
  	ELSE CONCAT(MISIDO_NOTA,CONCAT( '; ', N130.NOTE_INFO))
  END AS NOTA_IDONEITA,  
  CASE 
  	WHEN MISSAL_NOTA IS NULL THEN N115.NOTE_INFO
  	ELSE concat('Lang. ', concat(MISSAL_NOTA, CONCAT('; ', N115.NOTE_INFO)))
  END AS NOTA_ATTUAZIONE_LANG,
  CASE 
  	WHEN MISOST_NOTA IS NULL THEN N125.NOTE_INFO
  	ELSE concat('Lang. ', concat(MISOST_NOTA, CONCAT('; ', N125.NOTE_INFO)))
  END AS NOTA_OSTATIVA_LANG,
  CASE 
  	WHEN MISIDO_NOTA IS NULL THEN N130.NOTE_INFO
  	ELSE concat('Lang. ', concat(MISIDO_NOTA, concat('; ', N130.NOTE_INFO)))
  END AS NOTA_IDONEITA_LANG,
  PDO.THRU_DATE AS DATA_RIFERIMENTO,
  ARE.WORK_EFFORT_ID as ARE_ID,
  PRO.WORK_EFFORT_ID AS PRO_ID,
  PRO.ORG_UNIT_ID AS PRO_RESP,
  FAS.WORK_EFFORT_ID AS FAS_ID,
  FAS.ORG_UNIT_ID AS FAS_RESP,
  RIS.WORK_EFFORT_ID AS RIS_ID,
  RIS.ORG_UNIT_ID AS RIS_RESP,
  MIS.WORK_EFFORT_ID AS MIS_ID,
  MIS.ORG_UNIT_ID AS MIS_RESP,
  MIS.WORK_EFFORT_PURPOSE_TYPE_ID AS MIS_TIP  
FROM WORK_EFFORT MIS
INNER JOIN WORK_EFFORT_PURPOSE_TYPE TIP ON TIP.WORK_EFFORT_PURPOSE_TYPE_ID = MIS.WORK_EFFORT_PURPOSE_TYPE_ID 
INNER JOIN WORK_EFFORT_TYPE MISPDO ON MISPDO.WORK_EFFORT_TYPE_ID = MIS.WORK_EFFORT_TYPE_ID 
INNER JOIN CUSTOM_TIME_PERIOD PDO ON PDO.PERIOD_TYPE_ID = MISPDO.PERIOD_TYPE_ID AND PDO.FROM_DATE <= MIS.ESTIMATED_COMPLETION_DATE AND PDO.THRU_DATE >= MIS.ESTIMATED_START_DATE
LEFT JOIN 
   (select WORK_EFFORT_ID, TRANSACTION_DATE, MISSAL_NOTA, MISOST_NOTA, MISIDO_NOTA, max(MISSAL_AMOUNT) as MISSAL_AMOUNT, max(MISIDO_AMOUNT) as MISIDO_AMOUNT, max(MISOST_AMOUNT) as MISOST_AMOUNT from
   (SELECT WEM.WORK_EFFORT_ID, ATT.TRANSACTION_DATE, 
    case when ACC.ACCOUNT_CODE = 'CORM10.SAL' then ATE.AMOUNT else null end as MISSAL_AMOUNT,
    case when ACC.ACCOUNT_CODE = 'CORM30.IDO' then ATE.AMOUNT else null end as MISIDO_AMOUNT,
    case when ACC.ACCOUNT_CODE = 'CORM20.OST' then ATE.AMOUNT else null end as MISOST_AMOUNT,
    case when ACC.ACCOUNT_CODE = 'CORM10.SAL' then RSC.UOM_DESCR else null end as MISSAL_DESCR,
    case when ACC.ACCOUNT_CODE = 'CORM30.IDO' then RSC.UOM_DESCR else null end as MISIDO_DESCR,
    case when ACC.ACCOUNT_CODE = 'CORM20.OST' then RSC.UOM_DESCR else null end as MISOST_DESCR,
    case when ACC.ACCOUNT_CODE = 'CORM10.SAL' then ATT.DESCRIPTION else null end as MISSAL_NOTA,
    case when ACC.ACCOUNT_CODE = 'CORM20.OST' then ATT.DESCRIPTION else null end as MISOST_NOTA,
    case when ACC.ACCOUNT_CODE = 'CORM30.IDO' then ATT.DESCRIPTION else null end as MISIDO_NOTA
    FROM WORK_EFFORT_MEASURE WEM
    INNER JOIN ACCTG_TRANS_ENTRY ATE ON ATE.VOUCHER_REF = WEM.WORK_EFFORT_MEASURE_ID
    INNER JOIN ACCTG_TRANS ATT ON ATT.ACCTG_TRANS_ID = ATE.ACCTG_TRANS_ID 
    INNER JOIN GL_ACCOUNT ACC ON ACC.GL_ACCOUNT_ID = ATE.GL_ACCOUNT_ID
    INNER JOIN WORK_EFFORT_MEAS_RAT_SC RSC ON RSC.WORK_EFFORT_MEASURE_ID = WEM.WORK_EFFORT_MEASURE_ID AND RSC.UOM_RATING_VALUE = ATE.AMOUNT 
    WHERE ACC.ACCOUNT_CODE in ( 'CORM10.SAL' , 'CORM30.IDO' , 'CORM20.OST' ) 
    ) MIS1 group by WORK_EFFORT_ID, TRANSACTION_DATE, MISSAL_NOTA, MISOST_NOTA, MISIDO_NOTA
    ) MIS2 ON MIS2.WORK_EFFORT_ID = MIS.WORK_EFFORT_ID AND MIS2.TRANSACTION_DATE = PDO.THRU_DATE
LEFT JOIN WORK_EFFORT_NOTE_VIEW N115 ON N115.WORK_EFFORT_ID = MIS.WORK_EFFORT_ID AND N115.SEQUENCE_ID = 115 and N115.NOTE_DATE_TIME <= PDO.THRU_DATE 
	and N115.NOTE_DATE_TIME >= PDO.FROM_DATE
LEFT JOIN WORK_EFFORT_NOTE_VIEW N125 ON N125.WORK_EFFORT_ID = MIS.WORK_EFFORT_ID AND N125.SEQUENCE_ID = 125 and N125.NOTE_DATE_TIME <= PDO.THRU_DATE 
	and N125.NOTE_DATE_TIME >= PDO.FROM_DATE
LEFT JOIN WORK_EFFORT_NOTE_VIEW N130 ON N130.WORK_EFFORT_ID = MIS.WORK_EFFORT_ID AND N130.SEQUENCE_ID = 130 and N130.NOTE_DATE_TIME <= PDO.THRU_DATE 
	and N130.NOTE_DATE_TIME >= PDO.FROM_DATE
INNER JOIN WORK_EFFORT_ASSOC RISMIS ON RISMIS.WORK_EFFORT_ID_TO = MIS.WORK_EFFORT_ID 
INNER JOIN WORK_EFFORT RIS ON RIS.WORK_EFFORT_ID = RISMIS.WORK_EFFORT_ID_FROM and RIS.WORK_EFFORT_REVISION_ID is null
INNER JOIN WORK_EFFORT_ASSOC FASRIS ON FASRIS.WORK_EFFORT_ID_TO = RIS.WORK_EFFORT_ID 
INNER JOIN WORK_EFFORT FAS ON FAS.WORK_EFFORT_ID = FASRIS.WORK_EFFORT_ID_FROM and FAS.WORK_EFFORT_REVISION_ID is null
INNER JOIN WORK_EFFORT_ASSOC PROFAS ON PROFAS.WORK_EFFORT_ID_TO = FAS.WORK_EFFORT_ID
INNER JOIN WORK_EFFORT PRO ON PRO.WORK_EFFORT_ID = PROFAS.WORK_EFFORT_ID_FROM and PRO.WORK_EFFORT_REVISION_ID is null
INNER JOIN WORK_EFFORT_ASSOC AREPRO ON AREPRO.WORK_EFFORT_ID_TO = PRO.WORK_EFFORT_ID 
INNER JOIN WORK_EFFORT ARE ON ARE.WORK_EFFORT_ID = AREPRO.WORK_EFFORT_ID_FROM and ARE.WORK_EFFORT_REVISION_ID is null
WHERE MIS.WORK_EFFORT_REVISION_ID is null
  and RISMIS.WORK_EFFORT_ASSOC_TYPE_ID = '15APPRO'
  AND FASRIS.WORK_EFFORT_ASSOC_TYPE_ID = '15APPRO'
  AND PROFAS.WORK_EFFORT_ASSOC_TYPE_ID = '15APPRO'
  AND AREPRO.WORK_EFFORT_ASSOC_TYPE_ID = '15APPPC';