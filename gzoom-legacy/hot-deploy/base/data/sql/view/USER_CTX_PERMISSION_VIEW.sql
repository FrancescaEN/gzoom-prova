CREATE OR REPLACE VIEW USER_CTX_PERMISSION_VIEW
       (USER_LOGIN_ID, PARTY_ID, ORGANIZATION_ID, USER_CTX, CTX_PERMISSION, IS_ORG, IS_SUP, IS_TOP, IS_ROLE, IS_VIEW, ROOT_ENABLED)
AS SELECT CXL.USER_LOGIN_ID AS USER_LOGIN_ID,
CXL.PARTY_ID,
CXL.ORGANIZATION_ID,
CXL.USER_CTX AS USER_CTX,
       (CASE WHEN MIN(CXL.PERMISSION_LEVEL) = 0 THEN '_ADMIN'
             WHEN MIN(CXL.PERMISSION_LEVEL) = 1 THEN '_RESP'
             WHEN MIN(CXL.PERMISSION_LEVEL) = 2 THEN '_VIEW'
             ELSE '_NONE' END ) AS CTX_PERMISSION,
       (CASE WHEN MIN(CXL.PERMISSION_LEVEL) = 1 AND MAX(CXL.PERMISSION_ORG)  = 1 THEN 1
             ELSE 0 END) AS IS_ORG,
       (CASE WHEN MIN(CXL.PERMISSION_LEVEL) = 1 AND MAX(CXL.PERMISSION_SUP)  = 1 THEN 1
             ELSE 0 END) AS IS_SUP,
       (CASE WHEN MIN(CXL.PERMISSION_LEVEL) = 1 AND MAX(CXL.PERMISSION_TOP)  = 1 THEN 1
             ELSE 0 END) AS IS_TOP,
       (CASE WHEN MIN(CXL.PERMISSION_LEVEL) = 1 AND MAX(CXL.PERMISSION_ROLE) = 1 THEN 1
             ELSE 0 END) AS IS_ROLE,
       (CASE WHEN MIN(CXL.PERMISSION_LEVEL) = 1 AND MAX(CXL.PERMISSION_VIEW) = 1 THEN 1
             ELSE 0 END) AS IS_VIEW,
       (CASE WHEN MIN(CXL.PERMISSION_LEVEL) = 1 AND MAX(CXL.PERMISSION_ROOT) = 1 THEN 1
             ELSE 0 END) AS ROOT_ENABLED
FROM
(SELECT UL.USER_LOGIN_ID AS USER_LOGIN_ID, UL.PARTY_ID AS PARTY_ID,
UP.USER_PREF_VALUE as ORGANIZATION_ID,
(CASE WHEN SGP.PERMISSION_ID LIKE 'BSCPERF%'    THEN 'CTX_BS'
      WHEN SGP.PERMISSION_ID LIKE 'CDGPERF%'    THEN 'CTX_CG'
      WHEN SGP.PERMISSION_ID LIKE 'COMMON%'     THEN 'CTX_BA'
      WHEN SGP.PERMISSION_ID LIKE 'ACCOUNTING%' THEN 'CTX_AC'
      WHEN SGP.PERMISSION_ID LIKE 'CORPERF%'    THEN 'CTX_CO'
      WHEN SGP.PERMISSION_ID LIKE 'DIRIGPERF%'  THEN 'CTX_DI'
      WHEN SGP.PERMISSION_ID LIKE 'EMPLPERF%'   THEN 'CTX_EP'
      WHEN SGP.PERMISSION_ID LIKE 'GDPRPERF%'   THEN 'CTX_GD'
      WHEN SGP.PERMISSION_ID LIKE 'ORGPERF%'    THEN 'CTX_OR'
      WHEN SGP.PERMISSION_ID LIKE 'PARTPERF%'   THEN 'CTX_PA'
      WHEN SGP.PERMISSION_ID LIKE 'PARTY%'      THEN 'CTX_PY'
      WHEN SGP.PERMISSION_ID LIKE 'PROCPERF%'   THEN 'CTX_PR'
      WHEN SGP.PERMISSION_ID LIKE 'RENDPERF%'   THEN 'CTX_RE'
      WHEN SGP.PERMISSION_ID LIKE 'TRASPERF%'   THEN 'CTX_TR'
      WHEN SGP.PERMISSION_ID LIKE 'WORKEFFORT%' THEN 'CTX_WE'
      ELSE 'CTX_ERR' END) AS USER_CTX,
(CASE WHEN SGP.PERMISSION_ID LIKE '%PERF%MGR_ADMIN'  THEN 0
      WHEN SGP.PERMISSION_ID LIKE '%PERF%ORG_ADMIN'  THEN 1
      WHEN SGP.PERMISSION_ID LIKE '%PERF%ROLE_ADMIN' THEN 1
      WHEN SGP.PERMISSION_ID LIKE '%PERF%SUP_ADMIN'  THEN 1
      WHEN SGP.PERMISSION_ID LIKE '%PERF%TOP_ADMIN'  THEN 1
      WHEN SGP.PERMISSION_ID LIKE '%PERF%VIEW_ADMIN' THEN 2
      WHEN SGP.PERMISSION_ID = 'PARTYMGR_ADMIN'      THEN 0
      WHEN SGP.PERMISSION_ID = 'COMMON_ADMIN'        THEN 0
      WHEN SGP.PERMISSION_ID = 'WORKEFFORTMGR_ADMIN' THEN 0
      WHEN SGP.PERMISSION_ID = 'ACCOUNTING_ADMIN'    THEN 0
      WHEN SGP.PERMISSION_ID = 'ACCOUNTINGORG_ADMIN' THEN 1
      WHEN SGP.PERMISSION_ID = 'PARTYORG_ADMIN'      THEN 1
      ELSE 3 END) AS PERMISSION_LEVEL,
(CASE WHEN SGP.PERMISSION_ID LIKE '%PERF%ORG_ADMIN' THEN 1
      ELSE 0 END) AS PERMISSION_ORG,
(CASE WHEN SGP.PERMISSION_ID LIKE '%PERF%ROLE_ADMIN' THEN 1
      ELSE 0 END) AS PERMISSION_ROLE,
(CASE WHEN SGP.PERMISSION_ID LIKE '%PERF%SUP_ADMIN' THEN 1
      ELSE 0 END) AS PERMISSION_SUP,
(CASE WHEN SGP.PERMISSION_ID LIKE '%PERF%TOP_ADMIN' THEN 1
      ELSE 0 END) AS PERMISSION_TOP,
(CASE WHEN SGP.PERMISSION_ID LIKE '%PERF%VIEW_ADMIN' THEN 1
      ELSE 0 END) AS PERMISSION_VIEW,
(CASE WHEN SGP.PERMISSION_ID LIKE '%PERF%ROOT' THEN 1
      ELSE 0 END) AS PERMISSION_ROOT
FROM USER_LOGIN_SECURITY_GROUP ULSG
INNER JOIN USER_LOGIN UL ON UL.USER_LOGIN_ID = ULSG.USER_LOGIN_ID
left OUTER JOIN USER_PREFERENCE UP ON UL.USER_LOGIN_ID = UP.USER_LOGIN_ID and USER_PREF_GROUP_TYPE_ID = 'GLOBAL_PREFERENCES'
and USER_PREF_TYPE_ID = 'ORGANIZATION_PARTY'
INNER JOIN SECURITY_GROUP_PERMISSION SGP ON SGP.GROUP_ID = ULSG.GROUP_ID
WHERE (SGP.PERMISSION_ID LIKE '%PERF%MGR_ADMIN'
    OR SGP.PERMISSION_ID LIKE '%PERF%ORG_ADMIN'
    OR SGP.PERMISSION_ID LIKE '%PERF%ROLE_ADMIN'
    OR SGP.PERMISSION_ID LIKE '%PERF%SUP_ADMIN'
    OR SGP.PERMISSION_ID LIKE '%PERF%TOP_ADMIN'
    OR SGP.PERMISSION_ID LIKE '%PERF%VIEW_ADMIN'
    OR SGP.PERMISSION_ID LIKE '%PERF%ROOT'
    OR SGP.PERMISSION_ID IN
    ('PARTYMGR_ADMIN', 'PARTYORG_ADMIN', 'COMMON_ADMIN', 'ACCOUNTINGORG_ADMIN', 'WORKEFFORTMGR_ADMIN', 'ACCOUNTING_ADMIN'))
   AND ULSG.THRU_DATE IS NULL) CXL
WHERE CXL.USER_CTX <> 'CTX_ERR' AND CXL.PERMISSION_LEVEL < 3
GROUP BY CXL.USER_LOGIN_ID, CXL.PARTY_ID, CXL.ORGANIZATION_ID, CXL.USER_CTX;