CREATE VIEW COR_PRO_DETAIL_VIEW AS 
SELECT 
  PDO.CUSTOM_TIME_PERIOD_CODE AS ANNO,
  ARE.ETCH AS ETCH_AREA_RISCHIO,
  ARE.WORK_EFFORT_NAME AS AREA_RISCHIO,
  PRO.SOURCE_REFERENCE_ID AS COD_PROCESSO,
  PRO.ETCH AS ETCH_PROCESSO,
  PRO.WORK_EFFORT_NAME AS PROCESSO, 
  concat('Lang. ',PDO.CUSTOM_TIME_PERIOD_CODE) AS ANNO_LANG,
  concat('Lang. ',ARE.WORK_EFFORT_NAME)  AS AREA_RISCHIO_LANG,
  concat('Lang. ',PRO.WORK_EFFORT_NAME)  AS PROCESSO_LANG, 
  SCORE.AMOUNT AS PRO_SCORE,
  case when SCORE.THRU_VALUE is null then 0 else SCORE.THRU_VALUE end as RISK_ID,
  case when SCORE.COMMENTS is null then 'n/a' else SCORE.COMMENTS end AS PRO_RISK,
  case when SCORE.COMMENTS is null then 'n/a' else concat('Lang. ',SCORE.COMMENTS) end AS PRO_RISK_LANG,
  PDO.THRU_DATE AS DATA_RIFERIMENTO,
  ARE.WORK_EFFORT_ID as ARE_ID,
  PRO.WORK_EFFORT_ID AS PRO_ID,
  PRO.ORG_UNIT_ID AS PRO_RESP
FROM WORK_EFFORT PRO
INNER JOIN WORK_EFFORT_TYPE PROPDO ON PROPDO.WORK_EFFORT_TYPE_ID = PRO.WORK_EFFORT_TYPE_ID 
INNER JOIN CUSTOM_TIME_PERIOD PDO ON PDO.PERIOD_TYPE_ID = PROPDO.PERIOD_TYPE_ID 
      AND PDO.FROM_DATE <= PRO.ESTIMATED_COMPLETION_DATE AND PDO.THRU_DATE >= PRO.ESTIMATED_START_DATE 
LEFT JOIN 
  (SELECT WEM.WORK_EFFORT_ID, ATT.TRANSACTION_DATE, ATE.AMOUNT, URV.COMMENTS , concat('Lang. ',URV.COMMENTS) as COMMENTS_LANG, URV.THRU_VALUE
   FROM WORK_EFFORT_MEASURE WEM
   INNER JOIN WORK_EFFORT WE ON WE.WORK_EFFORT_ID = WEM.WORK_EFFORT_ID
   INNER JOIN WORK_EFFORT_TYPE WET ON WET.WORK_EFFORT_TYPE_ID = WE.WORK_EFFORT_TYPE_ID
   INNER JOIN ACCTG_TRANS_ENTRY ATE ON ATE.VOUCHER_REF = WEM.WORK_EFFORT_MEASURE_ID and ate.work_effort_revision_id is null
   INNER JOIN ACCTG_TRANS ATT ON ATT.ACCTG_TRANS_ID = ATE.ACCTG_TRANS_ID and att.work_effort_revision_id is null
   INNER JOIN GL_ACCOUNT ACC ON ACC.GL_ACCOUNT_ID = ATE.GL_ACCOUNT_ID
   INNER JOIN UOM_RANGE_VALUES URV ON URV.UOM_RANGE_ID = WET.UOM_RANGE_SCORE_ID AND URV.FROM_VALUE <= ATE.AMOUNT AND URV.THRU_VALUE >= ATE.AMOUNT
   WHERE WEM.GL_ACCOUNT_ID = 'SCORE' AND ATE.GL_FISCAL_TYPE_ID = 'CORRIS') SCORE ON SCORE.WORK_EFFORT_ID = PRO.WORK_EFFORT_ID AND SCORE.TRANSACTION_DATE = PDO.THRU_DATE
INNER JOIN WORK_EFFORT_ASSOC AREPRO ON AREPRO.WORK_EFFORT_ID_TO = PRO.WORK_EFFORT_ID 
	and arepro.work_effort_revision_id is null
INNER JOIN WORK_EFFORT ARE ON ARE.WORK_EFFORT_ID = AREPRO.WORK_EFFORT_ID_FROM
WHERE AREPRO.WORK_EFFORT_ASSOC_TYPE_ID = '15APPPC' 
  and pro.work_effort_revision_id is null
  AND PRO.WORK_EFFORT_TYPE_ID = '15AP2SAR';